def application_environment(values=None):
    environment = {
        name: os.environ[name]
        for name in APPLICATION_SETTINGS | RUNTIME_SETTINGS
        if name in os.environ
    }
    environment.setdefault("PATH", os.defpath)
    environment.update({
        name: value for name, value in (values or {}).items()
        if name in APPLICATION_SETTINGS | RUNTIME_SETTINGS
    })
    return environment
